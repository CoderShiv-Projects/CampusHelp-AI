CREATE OR REPLACE PACKAGE pkg_ticket_workflow AS
  -- Custom exceptions (raised via RAISE_APPLICATION_ERROR with these codes)
  e_ticket_not_found   EXCEPTION; PRAGMA EXCEPTION_INIT(e_ticket_not_found,   -20001);
  e_invalid_transition EXCEPTION; PRAGMA EXCEPTION_INIT(e_invalid_transition, -20002);
  e_not_authorized     EXCEPTION; PRAGMA EXCEPTION_INIT(e_not_authorized,     -20003);
  e_invalid_input      EXCEPTION; PRAGMA EXCEPTION_INIT(e_invalid_input,      -20004);

  -- Age of a ticket in hours (to p_resolved if given, otherwise to now)
  FUNCTION get_ticket_age(p_created IN TIMESTAMP, p_resolved IN TIMESTAMP DEFAULT NULL) RETURN NUMBER;
  -- SLA target in hours by priority (Critical 4, High 24, Medium 72, Low 120)
  FUNCTION get_sla_hours(p_priority IN VARCHAR2) RETURN NUMBER;
  -- Deterministic safety rule: 'Y' if text mentions fire, sparking, gas leak, flooding...
  FUNCTION is_emergency(p_title IN VARCHAR2, p_description IN CLOB) RETURN VARCHAR2;

  PROCEDURE create_ticket(p_title IN VARCHAR2, p_description IN CLOB, p_student_id IN NUMBER,
                          p_category IN VARCHAR2, p_department IN VARCHAR2, p_priority IN VARCHAR2,
                          p_location_id IN NUMBER, p_ticket_id OUT NUMBER, p_escalated OUT VARCHAR2);
  PROCEDURE record_ai_analysis(p_ticket_id IN NUMBER, p_model IN VARCHAR2, p_category IN VARCHAR2,
                               p_department IN VARCHAR2, p_priority IN VARCHAR2,
                               p_summary IN VARCHAR2, p_reason IN VARCHAR2);
  PROCEDURE assign_ticket(p_ticket_id IN NUMBER, p_assignee_id IN NUMBER, p_actor_id IN NUMBER,
                          p_category IN VARCHAR2 DEFAULT NULL, p_department IN VARCHAR2 DEFAULT NULL,
                          p_priority IN VARCHAR2 DEFAULT NULL);
  PROCEDURE update_ticket_status(p_ticket_id IN NUMBER, p_new_status IN VARCHAR2,
                                 p_actor_id IN NUMBER, p_note IN VARCHAR2 DEFAULT NULL);
  PROCEDURE resolve_ticket(p_ticket_id IN NUMBER, p_actor_id IN NUMBER, p_resolution_note IN VARCHAR2);
  PROCEDURE add_comment(p_ticket_id IN NUMBER, p_user_id IN NUMBER, p_body IN VARCHAR2);

  -- Reports
  PROCEDURE ticket_report(p_result OUT SYS_REFCURSOR);   -- per-department aggregates (ref cursor)
  PROCEDURE print_status_report;                         -- explicit cursor + DBMS_OUTPUT
END pkg_ticket_workflow;
