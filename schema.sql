-- --------------------------------------------------------------- 1. TABLES --
CREATE TABLE departments (
  dept_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          VARCHAR2(60)  NOT NULL CONSTRAINT uq_dept_name UNIQUE,
  contact_email VARCHAR2(120),
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE categories (
  category_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            VARCHAR2(40) NOT NULL CONSTRAINT uq_cat_name UNIQUE,
  default_dept_id NUMBER CONSTRAINT fk_cat_dept REFERENCES departments(dept_id),
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE campus_locations (
  location_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        VARCHAR2(80) NOT NULL CONSTRAINT uq_loc_name UNIQUE,
  building    VARCHAR2(60),
  created_at  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

-- Demo-only accounts: there is intentionally NO password column (role picker login).
CREATE TABLE users (
  user_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username   VARCHAR2(40) NOT NULL CONSTRAINT uq_user_name UNIQUE,
  full_name  VARCHAR2(80) NOT NULL,
  email      VARCHAR2(120),
  role       VARCHAR2(10) NOT NULL CONSTRAINT ck_user_role CHECK (role IN ('STUDENT','STAFF','ADMIN')),
  dept_id    NUMBER CONSTRAINT fk_user_dept REFERENCES departments(dept_id),
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT ck_staff_dept CHECK (role <> 'STAFF' OR dept_id IS NOT NULL)
);

CREATE TABLE tickets (
  ticket_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title           VARCHAR2(150) NOT NULL,
  description     CLOB NOT NULL,
  student_id      NUMBER NOT NULL CONSTRAINT fk_tkt_student  REFERENCES users(user_id),
  category_id     NUMBER NOT NULL CONSTRAINT fk_tkt_category REFERENCES categories(category_id),
  dept_id         NUMBER NOT NULL CONSTRAINT fk_tkt_dept     REFERENCES departments(dept_id),
  location_id     NUMBER CONSTRAINT fk_tkt_location REFERENCES campus_locations(location_id),
  priority        VARCHAR2(10) DEFAULT 'Medium' NOT NULL
                  CONSTRAINT ck_tkt_priority CHECK (priority IN ('Low','Medium','High','Critical')),
  status          VARCHAR2(15) DEFAULT 'Open' NOT NULL
                  CONSTRAINT ck_tkt_status CHECK (status IN ('Open','Assigned','In Progress','Resolved','Closed')),
  escalated_flag  CHAR(1) DEFAULT 'N' NOT NULL CONSTRAINT ck_tkt_esc CHECK (escalated_flag IN ('Y','N')),
  assigned_to     NUMBER CONSTRAINT fk_tkt_assignee REFERENCES users(user_id),
  resolution_note VARCHAR2(1000),
  last_actor      NUMBER,          -- set by PKG_TICKET_WORKFLOW; read by the history trigger
  last_note       VARCHAR2(500),   -- (keeps the trigger free of package state)
  created_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  updated_at      TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  resolved_at     TIMESTAMP
);
CREATE INDEX ix_tkt_student ON tickets(student_id);
CREATE INDEX ix_tkt_dept    ON tickets(dept_id);
CREATE INDEX ix_tkt_status  ON tickets(status);

CREATE TABLE ticket_history (
  history_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id  NUMBER NOT NULL CONSTRAINT fk_hist_ticket REFERENCES tickets(ticket_id) ON DELETE CASCADE,
  old_status VARCHAR2(15),
  new_status VARCHAR2(15) NOT NULL,
  changed_by NUMBER CONSTRAINT fk_hist_user REFERENCES users(user_id),
  note       VARCHAR2(500),
  changed_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_hist_ticket ON ticket_history(ticket_id);

CREATE TABLE ticket_comments (
  comment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id  NUMBER NOT NULL CONSTRAINT fk_cmt_ticket REFERENCES tickets(ticket_id) ON DELETE CASCADE,
  user_id    NUMBER NOT NULL CONSTRAINT fk_cmt_user   REFERENCES users(user_id),
  body       VARCHAR2(2000) NOT NULL,
  created_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_cmt_ticket ON ticket_comments(ticket_id);

CREATE TABLE ai_analyses (
  analysis_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ticket_id     NUMBER NOT NULL CONSTRAINT fk_ai_ticket REFERENCES tickets(ticket_id) ON DELETE CASCADE,
  model_name    VARCHAR2(80),
  ai_category   VARCHAR2(40),
  ai_department VARCHAR2(60),
  ai_priority   VARCHAR2(10),
  summary       VARCHAR2(600),
  reason        VARCHAR2(600),
  created_at    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX ix_ai_ticket ON ai_analyses(ticket_id);

