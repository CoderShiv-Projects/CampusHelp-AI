-- ---------------------------------------------------------------- 4. TRIGGER --
-- Single place where history is written: procedures only UPDATE tickets (never
-- insert history themselves), so a status change can never be logged twice.
CREATE OR REPLACE TRIGGER trg_ticket_history
AFTER INSERT OR UPDATE OF status, assigned_to, priority, dept_id ON tickets
FOR EACH ROW
BEGIN
  IF INSERTING THEN
    INSERT INTO ticket_history (ticket_id, old_status, new_status, changed_by, note)
    VALUES (:NEW.ticket_id, NULL, :NEW.status, NVL(:NEW.last_actor, :NEW.student_id),
            NVL(:NEW.last_note, 'Ticket created'));
  ELSIF :OLD.status <> :NEW.status
     OR NVL(:OLD.assigned_to, -1) <> NVL(:NEW.assigned_to, -1)
     OR :OLD.priority <> :NEW.priority
     OR :OLD.dept_id <> :NEW.dept_id THEN
    INSERT INTO ticket_history (ticket_id, old_status, new_status, changed_by, note)
    VALUES (:NEW.ticket_id, :OLD.status, :NEW.status, :NEW.last_actor, :NEW.last_note);
  END IF;
END;
