CREATE OR REPLACE PACKAGE BODY pkg_ticket_workflow AS

  c_priorities CONSTANT VARCHAR2(40) := '|Low|Medium|High|Critical|';
  c_emergency  CONSTANT VARCHAR2(300) :=
    '(^|[^[:alpha:]])(fire|smoke|gas leak|short[- ]?circuit|sparking|sparks|electric shock|electrocut[a-z]*|exposed wires?|flood(ed|ing)?|injur(y|ed)|collapse[a-z]*)([^[:alpha:]]|$)';

  -- ----- private helpers -----
  PROCEDURE fail(p_code IN PLS_INTEGER, p_msg IN VARCHAR2) IS
  BEGIN
    RAISE_APPLICATION_ERROR(p_code, p_msg);
  END fail;

  PROCEDURE load_user(p_user_id IN NUMBER, p_role OUT VARCHAR2, p_dept OUT NUMBER) IS
  BEGIN
    SELECT role, dept_id INTO p_role, p_dept FROM users WHERE user_id = p_user_id;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN fail(-20004, 'Unknown user id ' || p_user_id);
  END load_user;

  PROCEDURE check_priority(p_priority IN VARCHAR2) IS
  BEGIN
    IF p_priority IS NULL OR INSTR(c_priorities, '|' || p_priority || '|') = 0 THEN
      fail(-20004, 'Priority must be Low, Medium, High or Critical');
    END IF;
  END check_priority;

  FUNCTION category_id_of(p_name IN VARCHAR2) RETURN NUMBER IS
    l_id NUMBER;
  BEGIN
    SELECT category_id INTO l_id FROM categories WHERE LOWER(name) = LOWER(p_name);
    RETURN l_id;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      SELECT category_id INTO l_id FROM categories WHERE name = 'Other';
      RETURN l_id;
  END category_id_of;

  FUNCTION dept_id_of(p_name IN VARCHAR2) RETURN NUMBER IS
    l_id NUMBER;
  BEGIN
    SELECT dept_id INTO l_id FROM departments WHERE LOWER(name) = LOWER(p_name);
    RETURN l_id;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN
      SELECT dept_id INTO l_id FROM departments WHERE name = 'General Support';
      RETURN l_id;
  END dept_id_of;

  FUNCTION lock_ticket(p_ticket_id IN NUMBER) RETURN tickets%ROWTYPE IS
    l_t tickets%ROWTYPE;
  BEGIN
    SELECT * INTO l_t FROM tickets WHERE ticket_id = p_ticket_id FOR UPDATE;
    RETURN l_t;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN fail(-20001, 'Ticket ' || p_ticket_id || ' not found');
  END lock_ticket;

  -- Staff may act only on tickets of their own department; admins on any ticket.
  PROCEDURE require_staff(p_actor_id IN NUMBER, p_ticket_dept IN NUMBER) IS
    l_role users.role%TYPE;
    l_dept NUMBER;
  BEGIN
    load_user(p_actor_id, l_role, l_dept);
    IF l_role = 'ADMIN' OR (l_role = 'STAFF' AND l_dept = p_ticket_dept) THEN
      RETURN;
    END IF;
    fail(-20003, 'Only staff of the ticket''s department (or an admin) can do this');
  END require_staff;

  FUNCTION is_valid_transition(p_old IN VARCHAR2, p_new IN VARCHAR2) RETURN BOOLEAN IS
  BEGIN
    IF p_old = 'Open'        AND p_new IN ('Assigned','Closed')            THEN RETURN TRUE;
    ELSIF p_old = 'Assigned'    AND p_new IN ('In Progress','Closed')      THEN RETURN TRUE;
    ELSIF p_old = 'In Progress' AND p_new IN ('Assigned','Closed')         THEN RETURN TRUE;
    ELSIF p_old = 'Resolved'    AND p_new IN ('In Progress','Closed')      THEN RETURN TRUE;
    END IF;
    RETURN FALSE;
  END is_valid_transition;

  -- ----- public functions -----
  FUNCTION get_ticket_age(p_created IN TIMESTAMP, p_resolved IN TIMESTAMP DEFAULT NULL) RETURN NUMBER IS
    l_end TIMESTAMP := NVL(p_resolved, CAST(SYSTIMESTAMP AS TIMESTAMP));
    l_int INTERVAL DAY TO SECOND;
  BEGIN
    IF p_created IS NULL THEN RETURN NULL; END IF;
    l_int := l_end - p_created;
    RETURN ROUND(EXTRACT(DAY FROM l_int) * 24 + EXTRACT(HOUR FROM l_int)
                 + EXTRACT(MINUTE FROM l_int) / 60, 1);
  END get_ticket_age;

  FUNCTION get_sla_hours(p_priority IN VARCHAR2) RETURN NUMBER IS
  BEGIN
    RETURN CASE p_priority WHEN 'Critical' THEN 4 WHEN 'High' THEN 24 WHEN 'Medium' THEN 72 ELSE 120 END;
  END get_sla_hours;

  FUNCTION is_emergency(p_title IN VARCHAR2, p_description IN CLOB) RETURN VARCHAR2 IS
  BEGIN
    IF REGEXP_LIKE(p_title || ' ' || DBMS_LOB.SUBSTR(p_description, 4000, 1), c_emergency, 'i') THEN
      RETURN 'Y';
    END IF;
    RETURN 'N';
  END is_emergency;

  -- ----- public procedures -----
  PROCEDURE create_ticket(p_title IN VARCHAR2, p_description IN CLOB, p_student_id IN NUMBER,
                          p_category IN VARCHAR2, p_department IN VARCHAR2, p_priority IN VARCHAR2,
                          p_location_id IN NUMBER, p_ticket_id OUT NUMBER, p_escalated OUT VARCHAR2) IS
    l_role users.role%TYPE;
    l_dept NUMBER;
    l_prio VARCHAR2(10);
    l_category_id NUMBER;
  l_department_id NUMBER;
  BEGIN
    IF p_title IS NULL OR LENGTH(TRIM(p_title)) < 5 THEN
      fail(-20004, 'Title must be at least 5 characters');
    END IF;
    IF p_description IS NULL OR DBMS_LOB.GETLENGTH(p_description) < 10 THEN
      fail(-20004, 'Description must be at least 10 characters');
    END IF;
    load_user(p_student_id, l_role, l_dept);
    IF l_role <> 'STUDENT' THEN
      fail(-20003, 'Only students can submit complaints');
    END IF;
    l_prio := NVL(p_priority, 'Medium');
    check_priority(l_prio);
    p_escalated := is_emergency(p_title, p_description);   -- deterministic rule beats AI
    IF p_escalated = 'Y' THEN l_prio := 'Critical'; END IF;
    l_category_id := category_id_of(p_category);
    l_department_id := dept_id_of(p_department);
    INSERT INTO tickets (title, description, student_id, category_id, dept_id, location_id,
                         priority, escalated_flag, status, last_actor, last_note)
    VALUES (TRIM(p_title), p_description, p_student_id,
        l_category_id, l_department_id, p_location_id,
        l_prio, p_escalated, 'Open',
        p_student_id, 'Ticket created')
    RETURNING ticket_id INTO p_ticket_id;          -- trigger writes the first history row
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN ROLLBACK; RAISE;
  END create_ticket;

  PROCEDURE record_ai_analysis(p_ticket_id IN NUMBER, p_model IN VARCHAR2, p_category IN VARCHAR2,
                               p_department IN VARCHAR2, p_priority IN VARCHAR2,
                               p_summary IN VARCHAR2, p_reason IN VARCHAR2) IS
    l_cnt NUMBER;
  BEGIN
    SELECT COUNT(*) INTO l_cnt FROM tickets WHERE ticket_id = p_ticket_id;
    IF l_cnt = 0 THEN fail(-20001, 'Ticket ' || p_ticket_id || ' not found'); END IF;
    INSERT INTO ai_analyses (ticket_id, model_name, ai_category, ai_department, ai_priority, summary, reason)
    VALUES (p_ticket_id, SUBSTR(p_model, 1, 80), SUBSTR(p_category, 1, 40), SUBSTR(p_department, 1, 60),
            SUBSTR(p_priority, 1, 10), SUBSTR(p_summary, 1, 600), SUBSTR(p_reason, 1, 600));
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN ROLLBACK; RAISE;
  END record_ai_analysis;

  PROCEDURE assign_ticket(p_ticket_id IN NUMBER, p_assignee_id IN NUMBER, p_actor_id IN NUMBER,
                          p_category IN VARCHAR2 DEFAULT NULL, p_department IN VARCHAR2 DEFAULT NULL,
                          p_priority IN VARCHAR2 DEFAULT NULL) IS
    l_t      tickets%ROWTYPE;
    l_srole  users.role%TYPE;
    l_sdept  NUMBER;
    l_name   users.full_name%TYPE;
    l_cat    NUMBER;
    l_dept   NUMBER;
    l_prio   VARCHAR2(10);
    l_status VARCHAR2(15);
    l_note   VARCHAR2(500);
  BEGIN
    l_t := lock_ticket(p_ticket_id);
    require_staff(p_actor_id, l_t.dept_id);
    IF l_t.status IN ('Resolved', 'Closed') THEN
      fail(-20002, 'Cannot re-assign a ' || l_t.status || ' ticket');
    END IF;
    l_cat  := CASE WHEN p_category   IS NULL THEN l_t.category_id ELSE category_id_of(p_category)   END;
    l_dept := CASE WHEN p_department IS NULL THEN l_t.dept_id     ELSE dept_id_of(p_department)    END;
    l_prio := NVL(p_priority, l_t.priority);
    check_priority(l_prio);
    IF l_t.escalated_flag = 'Y' AND l_prio <> 'Critical' THEN
      fail(-20003, 'Emergency-flagged ticket cannot be downgraded from Critical');
    END IF;
    load_user(p_assignee_id, l_srole, l_sdept);
    IF l_srole <> 'STAFF' OR l_sdept <> l_dept THEN
      fail(-20004, 'Assignee must be a staff member of the ticket''s department');
    END IF;
    SELECT full_name INTO l_name FROM users WHERE user_id = p_assignee_id;
    l_status := CASE WHEN l_t.status = 'Open' THEN 'Assigned' ELSE l_t.status END;
    l_note := 'Assigned to ' || l_name;
    IF l_prio <> l_t.priority THEN l_note := l_note || '; priority ' || l_t.priority || ' -> ' || l_prio; END IF;
    IF l_dept <> l_t.dept_id  THEN l_note := l_note || '; department changed'; END IF;

    UPDATE tickets
       SET category_id = l_cat, dept_id = l_dept, priority = l_prio, assigned_to = p_assignee_id,
           status = l_status, last_actor = p_actor_id, last_note = l_note, updated_at = SYSTIMESTAMP
     WHERE ticket_id = p_ticket_id;                 -- trigger logs the change (once)
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN ROLLBACK; RAISE;
  END assign_ticket;

  PROCEDURE update_ticket_status(p_ticket_id IN NUMBER, p_new_status IN VARCHAR2,
                                 p_actor_id IN NUMBER, p_note IN VARCHAR2 DEFAULT NULL) IS
    l_t tickets%ROWTYPE;
  BEGIN
    l_t := lock_ticket(p_ticket_id);
    require_staff(p_actor_id, l_t.dept_id);
    IF p_new_status IS NULL OR p_new_status NOT IN ('Assigned', 'In Progress', 'Closed') THEN
      fail(-20004, 'Status must be Assigned, In Progress or Closed (use RESOLVE_TICKET to resolve)');
    END IF;
    IF NOT is_valid_transition(l_t.status, p_new_status) THEN
      fail(-20002, 'Invalid status change: ' || l_t.status || ' -> ' || p_new_status);
    END IF;
    IF p_new_status IN ('Assigned', 'In Progress') AND l_t.assigned_to IS NULL THEN
      fail(-20002, 'Assign the ticket to a staff member first');
    END IF;
    UPDATE tickets
       SET status = p_new_status,
           resolved_at = CASE WHEN l_t.status = 'Resolved' AND p_new_status <> 'Closed' THEN NULL ELSE resolved_at END,
           last_actor = p_actor_id,
           last_note = SUBSTR(NVL(p_note, 'Status changed to ' || p_new_status), 1, 500),
           updated_at = SYSTIMESTAMP
     WHERE ticket_id = p_ticket_id;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN ROLLBACK; RAISE;
  END update_ticket_status;

  PROCEDURE resolve_ticket(p_ticket_id IN NUMBER, p_actor_id IN NUMBER, p_resolution_note IN VARCHAR2) IS
    l_t tickets%ROWTYPE;
  BEGIN
    l_t := lock_ticket(p_ticket_id);
    require_staff(p_actor_id, l_t.dept_id);
    IF p_resolution_note IS NULL OR LENGTH(TRIM(p_resolution_note)) < 10 THEN
      fail(-20004, 'Resolution note must be at least 10 characters');
    END IF;
    IF l_t.status NOT IN ('Assigned', 'In Progress') THEN
      fail(-20002, 'Only Assigned or In Progress tickets can be resolved (current: ' || l_t.status || ')');
    END IF;
    UPDATE tickets
       SET status = 'Resolved', resolution_note = SUBSTR(TRIM(p_resolution_note), 1, 1000),
           resolved_at = SYSTIMESTAMP, last_actor = p_actor_id,
           last_note = 'Resolved: ' || SUBSTR(TRIM(p_resolution_note), 1, 200),
           updated_at = SYSTIMESTAMP
     WHERE ticket_id = p_ticket_id;
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN ROLLBACK; RAISE;
  END resolve_ticket;

  PROCEDURE add_comment(p_ticket_id IN NUMBER, p_user_id IN NUMBER, p_body IN VARCHAR2) IS
    l_t    tickets%ROWTYPE;
    l_role users.role%TYPE;
    l_dept NUMBER;
  BEGIN
    IF p_body IS NULL OR LENGTH(TRIM(p_body)) < 2 THEN fail(-20004, 'Comment is empty'); END IF;
    l_t := lock_ticket(p_ticket_id);
    load_user(p_user_id, l_role, l_dept);
    IF NOT (l_role = 'ADMIN'
            OR (l_role = 'STUDENT' AND l_t.student_id = p_user_id)
            OR (l_role = 'STAFF' AND l_dept = l_t.dept_id)) THEN
      fail(-20003, 'You cannot comment on this ticket');
    END IF;
    INSERT INTO ticket_comments (ticket_id, user_id, body)
    VALUES (p_ticket_id, p_user_id, SUBSTR(TRIM(p_body), 1, 2000));
    COMMIT;
  EXCEPTION
    WHEN OTHERS THEN ROLLBACK; RAISE;
  END add_comment;

  PROCEDURE ticket_report(p_result OUT SYS_REFCURSOR) IS
  BEGIN
    OPEN p_result FOR
      SELECT d.name AS department,
             COUNT(t.ticket_id) AS total_tickets,
             NVL(SUM(CASE WHEN t.status IN ('Open','Assigned','In Progress') THEN 1 ELSE 0 END), 0) AS active_tickets,
             NVL(SUM(CASE WHEN t.status IN ('Resolved','Closed') THEN 1 ELSE 0 END), 0) AS resolved_tickets,
             NVL(SUM(CASE WHEN t.priority = 'Critical' THEN 1 ELSE 0 END), 0) AS critical_tickets,
             ROUND(AVG(CASE WHEN t.resolved_at IS NOT NULL
                            THEN get_ticket_age(t.created_at, t.resolved_at) END), 1) AS avg_resolution_hours,
             NVL(SUM(CASE WHEN t.ticket_id IS NOT NULL
                           AND get_ticket_age(t.created_at, t.resolved_at) > get_sla_hours(t.priority)
                          THEN 1 ELSE 0 END), 0) AS sla_breaches
        FROM departments d LEFT JOIN tickets t ON t.dept_id = d.dept_id
       GROUP BY d.name
       ORDER BY COUNT(t.ticket_id) DESC, d.name;
  END ticket_report;

  PROCEDURE print_status_report IS
    CURSOR c_status IS
      SELECT status, COUNT(*) AS cnt FROM tickets GROUP BY status ORDER BY cnt DESC;
  BEGIN
    DBMS_OUTPUT.PUT_LINE('--- Tickets by status ---');
    FOR r IN c_status LOOP
      DBMS_OUTPUT.PUT_LINE(RPAD(r.status, 14) || r.cnt);
    END LOOP;
  END print_status_report;

END pkg_ticket_workflow;
