-- ------------------------------------------------------------------ 5. VIEW --
CREATE OR REPLACE VIEW v_ticket_overview AS
SELECT t.ticket_id, t.title, t.description, t.status, t.priority, t.escalated_flag,
       c.name AS category, d.name AS department, t.dept_id, t.category_id,
       l.name AS location, t.student_id, s.full_name AS student_name,
       t.assigned_to, a.full_name AS assignee_name, t.resolution_note,
       t.created_at, t.updated_at, t.resolved_at,
       pkg_ticket_workflow.get_ticket_age(t.created_at, t.resolved_at) AS age_hours,
       pkg_ticket_workflow.get_sla_hours(t.priority) AS sla_target_hours,
       CASE WHEN pkg_ticket_workflow.get_ticket_age(t.created_at, t.resolved_at)
                 > pkg_ticket_workflow.get_sla_hours(t.priority)
             AND NOT (t.status = 'Closed' AND t.resolved_at IS NULL)
            THEN 'Y' ELSE 'N' END AS sla_breached
  FROM tickets t
  JOIN categories c ON c.category_id = t.category_id
  JOIN departments d ON d.dept_id = t.dept_id
  JOIN users s ON s.user_id = t.student_id
  LEFT JOIN campus_locations l ON l.location_id = t.location_id
  LEFT JOIN users a ON a.user_id = t.assigned_to;

